"""levels/endless_pool.json -> supabase/functions/scores/endless_data.ts (the ranking server's copy of the pool).

    python tools/export_endless_data.py      (after tools/endless_pool.py; then redeploy the scores function)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import endless as E  # noqa: E402

pl = E.pool()
out = os.path.join(ROOT, "supabase", "functions", "scores", "endless_data.ts")
st = E.pool_stars()
stars = {}
for (t, lid) in sorted(st):
    stars.setdefault(str(t), {})[str(lid)] = st[(t, lid)]
data = {"version": E.ENDLESS_VERSION, "digest": E.pool_digest(), "tiers": {str(k): pl[k] for k in sorted(pl)}, "stars": stars}
with open(out, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/export_endless_data.py - do not edit\n")
    f.write(f"export const ENDLESS_POOL = {json.dumps(data, separators=(',', ':'))};\n")
print("written", out, "digest", data["digest"])
