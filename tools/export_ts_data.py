"""Export data for the TypeScript leaderboard function (supabase/functions/scores).

    python tools/export_ts_data.py

Writes
  supabase/functions/scores/levels_data.ts     level geometry + digests (no reference solutions)
  supabase/functions/scores/golden.json        Python results for many tap sequences (proves sim.ts == sim.py)
Re-run it whenever levels/ or sim.py change, then redeploy the function.
"""
import os
import sys
import json
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from sim import LevelData, replay, SIM_VERSION  # noqa: E402

OUT = os.path.join(ROOT, "supabase", "functions", "scores")
os.makedirs(OUT, exist_ok=True)

levels, digests = {}, {}
for i in range(1, 141):
    lvl = LevelData.load(i)
    d = {k: v for k, v in lvl.raw.items() if k not in ("ref_taps", "difficulty", "title")}
    levels[str(i)] = d
    digests[str(i)] = lvl.digest

with open(os.path.join(OUT, "levels_data.ts"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/export_ts_data.py - do not edit\n")
    f.write(f"export const SIM_VERSION_DATA = {SIM_VERSION};\n")
    f.write("// deno-lint-ignore no-explicit-any\nexport const LEVELS: Record<string, any> = ")
    json.dump(levels, f, separators=(",", ":"))
    f.write(";\nexport const DIGESTS: Record<string, string> = ")
    json.dump(digests, f, separators=(",", ":"))
    f.write(";\n")
    # levels that were rebuilt (levelgen/legacy_levels holds their previous files): a game that is not updated yet still
    # plays the old geometry, so its runs are replayed on that one instead of being refused with 409
    legacy = {}
    LEGACY_DIR = os.path.join(ROOT, "levelgen", "legacy_levels")
    for name in sorted(os.listdir(LEGACY_DIR)) if os.path.isdir(LEGACY_DIR) else []:
        with open(os.path.join(LEGACY_DIR, name), encoding="utf-8") as lf:
            raw = json.load(lf)
        old = LevelData(raw)
        if old.digest != digests.get(str(raw["id"])):
            legacy[old.digest] = {"level": raw["id"], "data": {k: v for k, v in raw.items() if k not in ("ref_taps", "difficulty", "title")}}
    f.write("// deno-lint-ignore no-explicit-any\nexport const LEGACY: Record<string, { level: number; data: any }> = ")
    json.dump(legacy, f, separators=(",", ":"))
    f.write(";\n")
    print("legacy level versions:", sorted(v["level"] for v in legacy.values()))


def snap(sim, res):
    o = sim.orbs
    return {
        "won": sim.won, "dead": sim.dead, "n": sim.n, "swaps": sim.swaps, "stars": sim.stars_collected,
        "near": sim.near_count, "combo": sim.combo_points, "t": sim.t, "smooth": sim.smooth,
        "orbs": [o[0].x, o[0].y, o[1].x, o[1].y], "total": res["level_total"] if res else None,
        "rank": res["rank"] if res else None,
    }


golden = []
rng = random.Random(2026)
for i in range(1, 141):
    lvl = LevelData.load(i)
    ref = lvl.raw["ref_taps"]
    variants = [ref]
    for k in range(3):                                   # nearly-right runs: die late, or win with other score
        variants.append(sorted(max(0, t + rng.randint(-2, 2)) for t in ref))
    if lvl.barriers or lvl.breakables or lvl.chasers or lvl.shrink or lvl.growth:      # extra coverage of the power-up gates
        for spread in (4, 7, 12):
            variants.append(sorted(max(0, t + rng.randint(-spread, spread)) for t in ref))
    variants.append(sorted(rng.sample(range(30, 900), 12)))          # garbage run
    for taps in variants:
        sim, res = replay(lvl, taps, max_seconds=max(90.0, lvl.par_time * 8))
        golden.append({"level": i, "taps": taps, "py": snap(sim, res)})
json.dump(golden, open(os.path.join(OUT, "golden.json"), "w"), separators=(",", ":"))
print("levels_data.ts + golden.json written:", len(golden), "cases,",
      sum(1 for g in golden if g["py"]["won"]), "wins,", sum(1 for g in golden if g["py"]["dead"]), "deaths")
