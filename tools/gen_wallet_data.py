"""Writes supabase/functions/scores/wallet_data.ts from the game's own catalogue, so the server charges and pays
exactly what the game shows. Run after changing skin prices, achievements, daily missions or diamond packs:

    python tools/gen_wallet_data.py

then redeploy the `scores` function."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import achievements          # noqa: E402
import daily_missions as dm  # noqa: E402
import shop                  # noqa: E402
import skin_catalog          # noqa: E402
import login_rewards         # noqa: E402
import weekly_missions as wm # noqa: E402
import events                # noqa: E402

data = {
    "SKIN_COST": dict(sorted(skin_catalog.COST.items())),
    "ACH_IDS": [a[0] for a in achievements.ACHIEVEMENTS],
    "DAILY": {"easy": dm.POOL_EASY, "medium": dm.POOL_MEDIUM, "hard": dm.POOL_HARD},
    "PACKS": {p[0]: p[1] for p in shop.DIAMOND_PACKS},
    "SHIELD_COST": shop.SHIELD_COST,
    "PREMIUM_SKINS": sorted(shop.SKIN_PRICE),
    "LOGIN_REWARDS": login_rewards.LOGIN_REWARDS,          # daily login calendar, day 1..7
    "WEEKLY": [[[m[3] for m in pool]] for pool in (wm.POOL_A, wm.POOL_B, wm.POOL_C)],   # rewards per pool slot
    "EVENTS": {e[0]: {"start": e[2], "end": e[3], "gems": [t[1] for t in e[5]]} for e in events.EVENTS},
}
out = ["// Generated by tools/gen_wallet_data.py from skin_catalog.py, achievements.py, daily_missions.py and shop.py.",
       "// Regenerate whenever prices, achievements or daily missions change - the server is the price authority."]
out += [f"export const {k} = {json.dumps(v, ensure_ascii=False)} as const;" for k, v in data.items()]
path = os.path.join(ROOT, "supabase", "functions", "scores", "wallet_data.ts")
with open(path, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("wrote", path)
